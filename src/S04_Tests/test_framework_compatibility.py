"""Direct tests of the non-clean shell default; explicit --clean is unchanged."""
import os
from pathlib import Path
import subprocess
import tempfile
import unittest

SCRIPTS = Path(__file__).resolve().parents[2] / '.agent/scripts'

class DefaultSyncTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        self.source = self.root / '.agent/skills/00-router/SKILL.md'
        self.source.parent.mkdir(parents=True)
        self.write_source('Original routing description')

    def write_source(self, description):
        self.source.write_text(f'---\nname: 00-router\ndescription: {description}\n---\nCanonical routing instructions.\n')

    def sync(self, target='both', expected=0):
        env = dict(os.environ)
        env.pop('CLEAN_ENV', None)
        result = subprocess.run(['bash', str(SCRIPTS / 'sync_agent_skill_wrappers.sh'), str(self.root), target], env=env, capture_output=True, text=True)
        self.assertEqual(result.returncode, expected, result.stdout + result.stderr)
        return result

    def test_default_sync_retains_unrelated_local_files(self):
        self.sync()
        paths = []
        for host in ('claude', 'codex'):
            local = self.root / f'.{host}/skills/local-analysis/SKILL.md'
            local.parent.mkdir()
            local.write_text('Author-owned local Skill.\n')
            asset = self.root / f'.{host}/skills/00-router/notes.txt'
            asset.write_text('Author-owned adjacent asset.\n')
            paths.extend((local, asset))
        before = [p.read_bytes() for p in paths]
        result = self.sync(expected=1)
        self.assertEqual([p.read_bytes() for p in paths], before)
        self.assertIn('exposure mismatch', result.stdout)
        self.assertNotIn('Done.', result.stdout)

    def test_single_host_sync_validates_only_requested_host(self):
        self.sync('claude')
        self.assertFalse((self.root / '.codex').exists())
        self.sync('codex')
        extra = self.root / '.codex/skills/01-project-brief/SKILL.md'
        extra.parent.mkdir()
        extra.write_text('Retained old internal wrapper.\n')
        self.sync('claude')
        self.sync('codex', expected=1)
        self.assertEqual(extra.read_text(), 'Retained old internal wrapper.\n')

    def test_stale_generated_internal_wrapper_is_reported_not_deleted(self):
        self.sync()
        internal = self.source.parent.parent / '01-project-brief/SKILL.md'
        internal.parent.mkdir()
        internal.write_text('---\nname: 01-project-brief\ndescription: Internal only\n---\n')
        stale = self.root / '.claude/skills/01-project-brief/SKILL.md'
        stale.parent.mkdir()
        content = '---\nname: 01-project-brief\ndescription: Internal only\n---\n\n<!-- Generated by .agent/scripts/sync_agent_skill_wrappers.sh. Do not edit manually. -->\n\n@../../../.agent/skills/01-project-brief/SKILL.md\n'
        stale.write_text(content)
        result = self.sync(expected=1)
        self.assertEqual(stale.read_text(), content)
        self.assertIn('01-project-brief', result.stdout)

    def test_default_validator_still_checks_both_hosts(self):
        self.sync('claude')
        result = subprocess.run(['python', str(SCRIPTS / 'validate_agent_skill_wrappers.py'), '--canonical', str(self.root / '.agent/skills'), '--claude', str(self.root / '.claude/skills'), '--codex', str(self.root / '.codex/skills')], capture_output=True, text=True)
        self.assertEqual(result.returncode, 1)
        self.assertIn('.codex/skills exposure mismatch', result.stdout)

    def test_default_sync_refreshes_canonical_description(self):
        self.sync()
        self.write_source('Updated routing description')
        self.sync()
        for host in ('claude', 'codex'):
            wrapper = self.root / f'.{host}/skills/00-router/SKILL.md'
            self.assertIn('description: Updated routing description', wrapper.read_text())
            self.assertIn('@../../../.agent/skills/00-router/SKILL.md', wrapper.read_text())

class SymlinkDestinationTests(unittest.TestCase):
    def fixture(self, base):
        root = base / 'repo'
        source = root / '.agent/skills/00-router/SKILL.md'
        source.parent.mkdir(parents=True)
        source.write_text('---\nname: 00-router\ndescription: Original routing\n---\n')
        self.assertEqual(self.run_sync(root).returncode, 0)
        return root, source

    def run_sync(self, root, target='both', clean=False):
        env = dict(os.environ)
        env.pop('CLEAN_ENV', None)
        args = ['bash', str(SCRIPTS / 'sync_agent_skill_wrappers.sh'), str(root), target]
        if clean:
            args.append('--clean')
        return subprocess.run(args, env=env, capture_output=True, text=True)

    def test_linked_destinations_fail_before_either_host_changes(self):
        import shutil
        for kind in ('file', 'broken_file', 'skill_directory', 'host_root', 'repo_root', 'repo_ancestor'):
            for clean in (False, True):
                with self.subTest(kind=kind, clean=clean), tempfile.TemporaryDirectory() as tmp:
                    base = Path(tmp)
                    root, source = self.fixture(base)
                    first = root / '.claude/skills/00-router/SKILL.md'
                    original = first.read_bytes()
                    source.write_text(source.read_text().replace('Original routing', 'Updated routing'))
                    external = base / 'external'
                    external.mkdir()
                    sentinel = external / 'SKILL.md'
                    sentinel.write_text('Author-owned target\n')
                    if kind in ('file', 'broken_file'):
                        link = root / '.codex/skills/00-router/SKILL.md'
                        link.unlink()
                        link.symlink_to(sentinel if kind == 'file' else external / 'missing.md')
                    elif kind in ('skill_directory', 'host_root'):
                        link = root / ('.codex/skills/00-router' if kind == 'skill_directory' else '.codex/skills')
                        shutil.rmtree(link)
                        link.symlink_to(external, target_is_directory=True)
                    elif kind == 'repo_root':
                        link = base / 'repo_alias'
                        link.symlink_to(root, target_is_directory=True)
                        root = link
                    else:
                        link = base / 'parent_alias'
                        link.symlink_to(base, target_is_directory=True)
                        root = link / 'repo'
                    result = self.run_sync(root, clean=clean)
                    self.assertNotEqual(result.returncode, 0, result.stdout + result.stderr)
                    self.assertIn('symlink', result.stderr)
                    self.assertEqual(first.read_bytes(), original)
                    self.assertEqual(sentinel.read_text(), 'Author-owned target\n')
                    self.assertTrue(link.is_symlink())

    def test_unselected_host_symlink_does_not_block_selected_host(self):
        with tempfile.TemporaryDirectory() as tmp:
            root, _ = self.fixture(Path(tmp))
            external = Path(tmp) / 'author.md'
            external.write_text('Author-owned target\n')
            link = root / '.codex/skills/00-router/SKILL.md'
            link.unlink()
            link.symlink_to(external)
            self.assertEqual(self.run_sync(root, target='claude').returncode, 0)
            self.assertEqual(external.read_text(), 'Author-owned target\n')

    def test_regular_explicit_clean_still_uses_original_behavior(self):
        with tempfile.TemporaryDirectory() as tmp:
            root, _ = self.fixture(Path(tmp))
            extra = root / '.claude/skills/local-only/SKILL.md'
            extra.parent.mkdir()
            extra.write_text('Explicitly cleaned test fixture\n')
            self.assertEqual(self.run_sync(root, target='claude', clean=True).returncode, 0)
            self.assertFalse(extra.exists())


if __name__ == '__main__':
    unittest.main()
